import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  IsIn,
  IsISO8601,
  IsInt,
  IsNotEmpty,
  IsOptional,
  IsString,
  IsUUID,
  Max,
  MaxLength,
  Min,
} from 'class-validator';
import { Type } from 'class-transformer';

import {
  CONVERSATION_KINDS,
  MESSAGE_MAX_LENGTH,
} from '../../../domain/conversation-access';

/**
 * Find or create a thread. Everything but `kind` may be left out where the
 * server can work it out: a ride names its operator and patient, and a driver
 * opening their own dispatch thread is themselves.
 */
export class OpenConversationDto {
  @ApiProperty({ enum: CONVERSATION_KINDS, enumName: 'ConversationKind' })
  @IsIn(CONVERSATION_KINDS)
  kind!: (typeof CONVERSATION_KINDS)[number];

  @ApiPropertyOptional({ type: String, format: 'uuid' })
  @IsOptional()
  @IsUUID()
  organizationId?: string;

  @ApiPropertyOptional({ type: String, format: 'uuid' })
  @IsOptional()
  @IsUUID()
  patientId?: string;

  @ApiPropertyOptional({ type: String, format: 'uuid' })
  @IsOptional()
  @IsUUID()
  driverId?: string;

  @ApiPropertyOptional({
    type: String,
    format: 'uuid',
    description: '`driverDriver`: the colleague. The caller is the other side.',
  })
  @IsOptional()
  @IsUUID()
  peerDriverId?: string;

  @ApiPropertyOptional({
    type: String,
    format: 'uuid',
    description:
      'Tie the thread to one trip. `dispatchFamily` and `dispatchDriver` only.',
  })
  @IsOptional()
  @IsUUID()
  rideId?: string;
}

export class SendMessageDto {
  @ApiProperty({ type: String, minLength: 1, maxLength: MESSAGE_MAX_LENGTH })
  @IsString()
  @IsNotEmpty()
  @MaxLength(MESSAGE_MAX_LENGTH)
  body!: string;

  @ApiProperty({
    type: String,
    format: 'uuid',
    description:
      'Generated by the client once per message and reused on every retry of it. A resend with the same id returns the message already stored.',
  })
  @IsUUID()
  clientMessageId!: string;
}

export class MessagePageQueryDto {
  @ApiPropertyOptional({ type: String, format: 'date-time' })
  @IsOptional()
  @IsISO8601()
  before?: string;

  @ApiPropertyOptional({ type: Number, minimum: 1, maximum: 100, default: 50 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(100)
  limit?: number;
}
